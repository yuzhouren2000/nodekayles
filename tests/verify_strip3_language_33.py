#!/usr/bin/env python3
"""Verify the exact value of the full 3x33 strip from the language-survey list.

Inputs:
  * data/strip3_language_survey_33.jsonl  (per-cell first-move values emitted by
    `src/cfast/strip3_language survey 33`; column-major v = 3c+r);
  * the a-sequence a(t) = value of the right-end-middle-gap strip, from
    data/strip3_survey.jsonl (t<=28) and data/strip3_a_ext.json (t=29..32);
  * the proven middle-move split formula a(i-1) xor a(n-i) for a move in the
    middle row at column i (notes/08).

Independently re-derives:
  * every middle-row option value from the a-sequence alone (old solver data);
  * board reflection symmetry of the full option list;
  * the mex of all 3n option values -> f(n), and the winning first moves.

Run: python3 tests/verify_strip3_language_33.py [--n 33] [--survey FILE]
"""

import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_N = 33


def load_a():
    a = {0: 0}
    for line in (ROOT / "data/strip3_survey.jsonl").read_text().splitlines():
        if line.strip():
            record = json.loads(line)
            a[record["n"]] = record["end_gap"]
    ext = json.loads((ROOT / "data/strip3_a_ext.json").read_text())["values"]
    for key, value in ext.items():
        a[int(key)] = value
    return a


def mex(values):
    present = set(values)
    g = 0
    while g in present:
        g += 1
    return g


def check_option_decomposition(a, problems):
    """Cross-check option-decomposition artifacts against the a-sequence:
    each artifact holds, for one or more A(t) boards, the SG values of all its
    first-move options (one job per option, generated by
    scripts/strip3_option_jobs.py); their mex is A(t).

    Both solver campaigns are checked when present: the old shared-memo
    solver (data/strip3_a_options.*) and the language solver's parallel batch
    (data/strip3_language_a_options.*). Only completed spans are checked, so
    the test stays usable while a campaign is still running.
    """
    reports = []
    for out_name, index_name, label in (
            ("strip3_a_options.out", "strip3_a_options_index.json", "old solver"),
            ("strip3_language_a_options.out", "strip3_language_a_options_index.json",
             "language solver")):
        out_file = ROOT / "data" / out_name
        index_file = ROOT / "data" / index_name
        if not (out_file.exists() and index_file.exists()):
            continue
        values = [int(token) for token in out_file.read_text().split()]
        spans = json.loads(index_file.read_text())
        checked = []
        for key, (start, stop) in sorted(spans.items(), key=lambda kv: int(kv[0])):
            if stop > len(values):
                continue
            got = mex(values[start:stop])
            if a.get(int(key)) != got:
                problems.append(f"{label} option decomposition: A({key}) "
                                f"mex={got}, a-sequence has {a.get(int(key))}")
            else:
                checked.append(f"A({key})={got}")
        if checked:
            reports.append(f"{label}: " + "、".join(checked))
    return reports if reports else None


def check_gaps_artifact(a, problems):
    """Cross-check the language solver's direct A(t)/D(t) run
    (`strip3_language gaps N`, artifact data/strip3_language_gaps_{32,33}.out)
    against the old solver's survey (t<=28, both sequences) and a_ext
    (A(29..31)).

    This is the second-method check for a(32): the language solver computes
    the whole a-sequence directly, and every value with an old-solver
    counterpart must agree before a(32) is accepted into the chain.
    """
    for name in ("strip3_language_gaps_33.out", "strip3_language_gaps_32.out"):
        path = ROOT / "data" / name
        if path.exists():
            break
    else:
        return None
    rows = {}
    for line in path.read_text().splitlines():
        parts = line.split()
        if len(parts) == 3:
            rows[int(parts[0])] = (int(parts[1]), int(parts[2]))
    if not rows:
        return f"{name}: artifact present but empty"
    old_a, old_d = {0: 0}, {0: 0}
    for line in (ROOT / "data/strip3_survey.jsonl").read_text().splitlines():
        if line.strip():
            record = json.loads(line)
            old_a[record["n"]] = record["end_gap"]
            old_d[record["n"]] = record["both_gaps"]
    matched = 0
    for t, (av, dv) in sorted(rows.items()):
        if t in old_a:
            if av != old_a[t]:
                problems.append(f"gaps artifact: A({t}) language {av}, "
                                f"old survey {old_a[t]}")
            elif dv != old_d[t]:
                problems.append(f"gaps artifact: D({t}) language {dv}, "
                                f"old survey {old_d[t]}")
            else:
                matched += 1
        elif t in a and av != a[t]:
            problems.append(f"gaps artifact: A({t}) language {av}, "
                            f"a_ext {a[t]}")
    newest = max(rows) if rows else 0
    a32 = rows.get(32, (None, None))[0]
    return (f"{name}: {matched}/28 A/D values match the old survey; "
            f"A(29..31) cross-checked against a_ext; "
            f"A({newest})={rows[newest][0]} D({newest})={rows[newest][1]} "
            f"(language-direct, a(32)={a32})")


def check_old_survey_invariants(problems):
    """Every old-solver survey record (n<=28) must satisfy the middle-move
    split formula against its own stored a-values and mex == grundy.

    This is the a-table the f(33) chain consumes; if any record were
    corrupted, the width-33 middle cross-check would silently inherit it.
    """
    records = [json.loads(line) for line in
               (ROOT / "data/strip3_survey.jsonl").read_text().splitlines()
               if line.strip()]
    a = {0: 0}
    for record in records:
        a[record["n"]] = record["end_gap"]
    checked = 0
    for record in records:
        n, options = record["n"], record["options"]
        for c in range(n):
            if options[3 * c + 1] != a[c] ^ a[n - 1 - c]:
                problems.append(f"old survey n={n} column {c + 1}: middle "
                                f"option {options[3 * c + 1]} != a({c})^a({n - 1 - c})")
        if mex(options) != record["grundy"]:
            problems.append(f"old survey n={n}: mex != recorded grundy")
        checked += 1
    return checked


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--n", type=int, default=DEFAULT_N)
    parser.add_argument("--survey", type=Path,
                        default=ROOT / "data/strip3_language_survey_33.jsonl")
    args = parser.parse_args()
    N = args.n

    survey = json.loads(args.survey.read_text())
    if survey["n"] != N:
        raise SystemExit(f"survey is for n={survey['n']}, expected {N}")
    options = survey["options"]
    assert len(options) == 3 * N, "option count"

    a = load_a()
    problems = []

    # 1) middle-row options recomputed from the old solver's a-sequence
    checked, pending = 0, []
    for c in range(N):
        want = a.get(c)
        other = a.get(N - 1 - c)
        got = options[3 * c + 1]
        if want is None or other is None:
            pending.append(c + 1)
            continue
        expect = want ^ other
        if got != expect:
            problems.append(f"middle column {c + 1}: survey {got}, "
                            f"a({c})^a({N - 1 - c})={expect}")
        else:
            checked += 1

    # 2) board reflection symmetry of the whole option list
    for c in range(N):
        for r in range(3):
            here = options[3 * c + r]
            mirror = options[3 * (N - 1 - c) + (2 - r)]
            if here != mirror:
                problems.append(f"reflection mismatch at (r{r + 1},c{c + 1}): "
                                f"{here} vs {mirror}")

    # 3) mex over all option values
    present = set(options)
    g = 0
    while g in present:
        g += 1

    winners = [(v // 3 + 1, v % 3 + 1) for v in range(3 * N) if options[v] == 0]
    print(f"survey mex = {g}; recorded grundy = {survey['grundy']}")
    if g != survey["grundy"]:
        problems.append(f"mex {g} != recorded grundy {survey['grundy']}")
    print(f"middle options cross-checked against the a-sequence: {checked}/{N}"
          + (f"; pending a-values for columns {pending}" if pending else ""))
    print(f"winning first moves (value-0 options): {winners}")
    print(f"option value set: {sorted(set(options))}")

    # 4) option-decomposition artifacts (old and language solver)
    decomposition = check_option_decomposition(a, problems)
    if decomposition is not None:
        for report in decomposition:
            print(f"option decomposition re-derived ({report})")
    else:
        print("option decomposition: no artifact yet")

    # 5) language-solver gaps run (direct A(t)/D(t) sequences)
    gaps_report = check_gaps_artifact(a, problems)
    if gaps_report is not None:
        print(gaps_report)

    # 6) old survey's own records satisfy the split formula and mex
    old_records = check_old_survey_invariants(problems)
    print(f"old survey invariants: {old_records} records (n<=28) satisfy "
          f"middle split formula and mex")

    if problems:
        print("PROBLEMS:")
        for p in problems:
            print("  " + p)
        return 1
    print(f"f({N}) = {g} verified from the survey certificate")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
