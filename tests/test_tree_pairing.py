"""Test the complete tree-pairing theorem against raw matching enumeration.

Every unlabelled tree up to order 12 is generated by attaching a leaf to every
vertex of every smaller tree. Deduplication uses an independent canonical
parenthesis word. Brute force enumerates ALL vertex matchings and checks the
original response condition, without using the structural classification.
"""

import argparse
import copy
from functools import lru_cache
from itertools import combinations_with_replacement
import json
import random
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
from tree_pairing import classify_tree, double_along_edge, from_edges, spider
from verify_tree_pairing import rooted_word, verify_result


def unlabelled_trees(limit):
    levels = {1: [[set()]]}
    for n in range(2, limit + 1):
        unique = {}
        for base in levels[n - 1]:
            for v in range(n - 1):
                adjacency = [set(ns) for ns in base] + [{v}]
                adjacency[v].add(n - 1)
                graph = {i: ns for i, ns in enumerate(adjacency)}
                key = min(rooted_word(graph, set(graph), root) for root in graph)
                unique.setdefault(key, adjacency)
        levels[n] = list(unique.values())
    return levels


def brute_exists(adjacency):
    n = len(adjacency)
    if n % 2:
        return False
    closed = [{v} | set(adjacency[v]) for v in range(n)]

    def matchings(remaining):
        if not remaining:
            yield []
            return
        a, *rest = remaining
        for i, b in enumerate(rest):
            for tail in matchings(rest[:i] + rest[i + 1:]):
                yield [(a, b), *tail]

    for pairs in matchings(list(range(n))):
        if any(b in adjacency[a] for a, b in pairs):
            continue
        phi = {a: b for a, b in pairs} | {b: a for a, b in pairs}
        for a, b in pairs:
            removed = closed[a] | closed[b]
            if {phi[v] for v in removed} != removed:
                break
        else:
            return True
    return False


def direct_grundy(adjacency):
    """No decomposition, pairing, canonicalisation or theorem shortcut."""
    n = len(adjacency)
    closed = [(1 << v) | sum(1 << u for u in adjacency[v]) for v in range(n)]

    @lru_cache(None)
    def value(mask):
        options = set()
        for v in range(n):
            if mask & (1 << v):
                options.add(value(mask & ~closed[v]))
        result = 0
        while result in options:
            result += 1
        return result

    return value((1 << n) - 1)


def expect_rejection(record):
    try:
        verify_result(record)
    except (ValueError, KeyError, TypeError):
        return
    raise AssertionError("false certificate/refutation accepted")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--max-order", type=int, default=12)
    parser.add_argument("--report", type=Path)
    args = parser.parse_args()
    if not 4 <= args.max_order <= 12:
        parser.error("max-order must be 4..12")
    levels = unlabelled_trees(args.max_order)
    known_counts = [0, 1, 1, 1, 2, 3, 6, 11, 23, 47, 106, 235, 551]
    assert [len(levels[n]) for n in range(1, args.max_order + 1)] == known_counts[1:args.max_order + 1]
    totals = {"trees": 0, "SAT": 0, "direct_sg": 0}
    by_order = []
    rng = random.Random(20261013)
    examples = []
    for n, trees in levels.items():
        positives = 0
        for adjacency in trees:
            record = classify_tree(adjacency)
            verify_result(record)
            expected = brute_exists(adjacency)
            assert (record["status"] == "SAT") == expected, record
            totals["trees"] += 1
            if expected:
                positives += 1
                assert direct_grundy(adjacency) == 0
                totals["direct_sg"] += 1
            # Relabel every tree to exercise arbitrary vertex numbering.
            permutation = list(range(n))
            rng.shuffle(permutation)
            edges = [(permutation[a], permutation[b]) for a, ns in enumerate(adjacency)
                     for b in ns if a < b]
            relabelled = classify_tree(from_edges(n, edges))
            verify_result(relabelled)
            assert relabelled["status"] == record["status"]
        by_order.append({"order": n, "trees": len(trees), "SAT": positives})
        totals["SAT"] += positives
        print(f"order {n}: {len(trees)} trees, {positives} admit fixed pairing", flush=True)

    constructed = 0
    for n, trees in levels.items():
        if n > 7:
            break
        for base in trees:
            for a, ns in enumerate(base):
                for b in ns:
                    adjacency = double_along_edge(base, (a, b))
                    record = classify_tree(adjacency)
                    assert record["status"] == "SAT"
                    verify_result(record)
                    constructed += 1
    spiders_checked = 0
    for arms in combinations_with_replacement(range(1, 7), 3):
        record = classify_tree(spider(arms))
        verify_result(record)
        expected = arms[0] == 1 and arms[2] == arms[1] + 2
        assert (record["status"] == "SAT") == expected, arms
        spiders_checked += 1
    for t in (1, 2, 3, 4, 10, 100, 1000):
        record = classify_tree(spider((1, t, t + 2)))
        assert record["status"] == "SAT"
        verify_result(record)
        if t <= 4:
            assert direct_grundy(spider((1, t, t + 2))) == 0
        if t <= 4:
            examples.append({**record, "label": f"spider(1,{t},{t+2})", "grundy": 0})
    for arms in ((1, 1, 1), (1, 2, 2), (2, 2, 3), (1, 1, 5)):
        record = classify_tree(spider(arms))
        assert record["status"] == "UNSAT"
        examples.append({**record, "label": f"spider{arms}"})
    path8 = from_edges(8, [(i, i + 1) for i in range(7)])
    assert direct_grundy(path8) == 0
    examples.append({**classify_tree(path8), "label": "P8 (P-position, no fixed pairing)", "grundy": 0})
    # A nonsymmetric branching base exercises more than the spider corollary.
    base = from_edges(5, [(0, 1), (1, 2), (1, 3), (3, 4)])
    example = classify_tree(double_along_edge(base, (0, 1)))
    example["label"] = "double of a branching five-vertex tree"
    example["grundy"] = direct_grundy(double_along_edge(base, (0, 1)))
    examples.append(example)

    forged = copy.deepcopy(examples[0])
    forged["pairs"].pop()
    expect_rejection(forged)
    forged = copy.deepcopy(examples[0])
    forged.update(status="UNSAT", reason="incompatible-rooted-halves")
    expect_rejection(forged)
    forged = copy.deepcopy(examples[0])
    forged["bridge"] = forged["pairs"][0]
    expect_rejection(forged)
    forged = copy.deepcopy(examples[0])
    forged["edges"].append(forged["edges"][0])
    expect_rejection(forged)
    report = {"format": "nodekayles-tree-pairing-audit-v1", "max_order": args.max_order,
              "method": "all unlabelled trees by leaf attachment; all perfect matchings; direct subset SG",
              "by_order": by_order, "totals": totals, "constructed_doubles": constructed,
              "spiders_checked": spiders_checked, "long_spider_t": 1000,
              "forged_records_rejected": 4, "examples": examples}
    if args.report:
        args.report.parent.mkdir(parents=True, exist_ok=True)
        args.report.write_text(json.dumps(report, indent=2) + "\n")
    print(f"verified {totals['trees']} trees against matching enumeration; "
          f"{constructed} edge doubles; {spiders_checked} spiders; forged records rejected")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
