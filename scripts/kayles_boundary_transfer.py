#!/usr/bin/env python3
"""Exact join/forget/rename operations on recursive Node Kayles interfaces.

All three-row induced strips are generated by one fully labelled 3x2 tile;
its 64 boundary deletions supply all adjacent-column masks.
The interface DAG can still grow exponentially; this is not a finite-state
or polynomial-time solver. Forgotten detached pieces are retained until the
entire boundary disappears, so generated forms need not match graph-normalized
forms syntactically. Their contextual SG semantics do match.
"""

import argparse
from functools import cache
import json

from kayles_boundary_algebra import BoundaryAlgebra, mex


class BoundaryTransfer(BoundaryAlgebra):
    """Compose complete interfaces without returning to their original graphs.

    Public operations consume and return (form, nimber) states. A join
    identifies only shared labels, retaining the union of the boundaries.
    Forgetting removes labels, not vertices. Renaming is injective.
    """

    def __init__(self):
        super().__init__()
        self._join = cache(self._join)
        self._forget = cache(self._forget)
        self._rename = cache(self._rename)
        self._value = cache(self._value)

    def state(self, graph, labels):
        graph, labels = tuple(graph), tuple(labels)
        if not graph and not labels:
            return 0, 0
        return super().state(graph, labels)

    def _check_state(self, state):
        if (not isinstance(state, tuple) or len(state) != 2
                or type(state[0]) is not int or not 0 <= state[0] < len(self.nodes)
                or type(state[1]) is not int or state[1] < 0):
            raise ValueError("state must be a valid (form, nonnegative nimber) pair")

    @staticmethod
    def _labels(labels):
        labels = tuple(labels)
        if any(type(label) is not int or label <= 0 for label in labels):
            raise ValueError("labels must be positive integers")
        return tuple(sorted(set(labels)))

    def _intern_node(self, node):
        if node not in self.intern:
            self.intern[node] = len(self.nodes)
            self.nodes.append(node)
        return self.intern[node]

    def value(self, state):
        """SG of the represented graph, with no additional external context."""
        self._check_state(state)
        form, offset = state
        return self._value(form) ^ offset

    def _value(self, form):
        if not form:
            return 0
        node = self.nodes[form]
        # Direct deletion is an interface query, never an additional game move.
        return mex(self._value(child) ^ offset
                   for _, (child, offset) in node[2] + node[3])

    def join(self, left, right):
        self._check_state(left)
        self._check_state(right)
        form, offset = self._join(left[0], right[0])
        return form, offset ^ left[1] ^ right[1]

    def _join(self, left, right):
        if left > right:
            return self._join(right, left)
        if not left:
            return right, 0
        a, b = self.nodes[left], self.nodes[right]
        ia, ib = set(a[0]), set(b[0])
        live = ia | ib

        def pair(sa, sb, removed=()):
            x, xx = sa
            y, yy = sb
            dx, kx = self.delete(x, tuple(removed))
            dy, ky = self.delete(y, tuple(removed))
            child, extra = self._join(dx, dy)
            return child, xx ^ yy ^ kx ^ ky ^ extra

        da, db, ma, mb = map(dict, (a[1], b[1], a[2], b[2]))
        direct, moves, internal = [], [], set()
        for label in sorted(live):
            direct.append((label, pair(da.get(label, (left, 0)),
                                       db.get(label, (right, 0)))))
            sa = ma.get(label, (left, 0))
            sb = mb.get(label, (right, 0))
            # A port move on one side can kill a port retained on the other.
            killed = ((ia - set(self.nodes[sa[0]][0]))
                      | (ib - set(self.nodes[sb[0]][0])))
            moves.append((label, pair(sa, sb, killed)))
        for source, other in ((a, right), (b, left)):
            for killed, state in source[3]:
                internal.add((killed, pair(state, (other, 0), killed)))
        node = (tuple(sorted(live)), tuple(direct), tuple(moves),
                tuple(sorted(internal)))
        return self._intern_node(node), 0

    def forget(self, state, labels):
        """Make these ports internal; they remain playable vertices."""
        self._check_state(state)
        removed = self._labels(labels)
        form, extra = self._forget(state[0], removed)
        return form, state[1] ^ extra

    def _forget(self, form, removed):
        if not form:
            return 0, 0
        a = self.nodes[form]
        live = set(a[0]) - set(removed)
        if live == set(a[0]):
            return form, 0
        if not live:
            return 0, self._value(form)

        def child(state):
            form, offset = state
            new, extra = self._forget(form, removed)
            return new, offset ^ extra

        direct = tuple((i, child(s)) for i, s in a[1] if i in live)
        moves = []
        internal = set()
        for label, state in a[2]:
            if label in live:
                moves.append((label, child(state)))
            else:
                killed = tuple(sorted(live - set(self.nodes[state[0]][0])))
                internal.add((killed, child(state)))
        for killed, state in a[3]:
            internal.add((tuple(i for i in killed if i in live), child(state)))
        node = (tuple(sorted(live)), direct, tuple(moves), tuple(sorted(internal)))
        return self._intern_node(node), 0

    def rename(self, state, mapping):
        """Relabel every live port; extra keys for absent ports are allowed."""
        self._check_state(state)
        pairs = tuple(mapping.items()) if isinstance(mapping, dict) else tuple(mapping)
        if any(not isinstance(p, (tuple, list)) or len(p) != 2 for p in pairs):
            raise ValueError("renaming requires label pairs")
        self._labels(i for i, _ in pairs)
        self._labels(j for _, j in pairs)
        mp = dict(pairs)
        live = self.nodes[state[0]][0]
        if len(mp) != len(pairs) or any(i not in mp for i in live):
            raise ValueError("renaming must specify each live port exactly once")
        if len({mp[i] for i in live}) != len(live):
            raise ValueError("renaming must be injective on live ports")
        return self._rename(state[0], tuple(sorted(mp.items()))), state[1]

    def _rename(self, form, mapping):
        if not form:
            return 0
        mp = dict(mapping)
        a = self.nodes[form]

        def child(state):
            form, offset = state
            return self._rename(form, mapping), offset

        node = (tuple(sorted(mp[i] for i in a[0])),
                tuple(sorted((mp[i], child(s)) for i, s in a[1])),
                tuple(sorted((mp[i], child(s)) for i, s in a[2])),
                tuple(sorted((tuple(sorted(mp[i] for i in killed)), child(s))
                             for killed, s in a[3])))
        return self._intern_node(node)


def validate_word(word):
    word = tuple(word)
    if any(type(w) is not int or not 0 <= w <= 7 for w in word):
        raise ValueError("column masks must be integers from 0 to 7")
    return word


def column_graph(word):
    """Return adjacency and (row, column) coordinates for a three-row word."""
    word = validate_word(word)
    cells = tuple((r, c) for c, w in enumerate(word) for r in range(3) if w >> r & 1)
    graph = tuple(sum(1 << j for j, (s, d) in enumerate(cells)
                      if abs(r - s) + abs(c - d) == 1) for r, c in cells)
    return graph, cells


class ThreeRowTransfer:
    """Generate any column word from one fully labelled six-vertex tile."""

    def __init__(self, algebra=None):
        self.algebra = algebra if algebra is not None else BoundaryTransfer()
        self._full_tile = cache(self._full_tile)
        self._tile = cache(self._tile)

    def _full_tile(self):
        graph, cells = column_graph((7, 7))
        return self.algebra.state(graph, tuple(3 * c + r + 1 for r, c in cells))

    def _tile(self, previous, column):
        full, offset = self._full_tile()
        removed = tuple(3 * c + r + 1 for c, w in enumerate((previous, column))
                        for r in range(3) if not w >> r & 1)
        form, extra = self.algebra.delete(full, removed)
        return form, offset ^ extra

    def append(self, state, previous, column):
        validate_word((previous, column))
        self.algebra._check_state(state)
        expected = tuple(r + 1 for r in range(3) if previous >> r & 1)
        if self.algebra.nodes[state[0]][0] != expected:
            raise ValueError("state boundary must match the previous column")
        joined = self.algebra.join(state, self._tile(previous, column))
        forgotten = self.algebra.forget(joined, (1, 2, 3))
        return self.algebra.rename(forgotten, {4: 1, 5: 2, 6: 3})

    def state(self, word):
        word = validate_word(word)
        state, previous = (0, 0), 0
        for column in word:
            state = self.append(state, previous, column)
            previous = column
        return state

    def value(self, word):
        return self.algebra.value(self.state(word))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--word", help="column masks written as digits 0..7")
    group.add_argument("--full", type=int, help="full 3xn sequence through this width")
    args = parser.parse_args()
    model = ThreeRowTransfer()
    if args.word is not None:
        if any(ch not in "01234567" for ch in args.word):
            parser.error("--word accepts only digits 0..7")
        word = tuple(map(int, args.word))
        state = model.state(word)
        print(json.dumps({"word": args.word, "SG": model.algebra.value(state),
                          "state": state, "nodes": len(model.algebra.nodes)}))
    else:
        if args.full < 0:
            parser.error("--full must be nonnegative")
        state, previous = (0, 0), 0
        for n in range(1, args.full + 1):
            state = model.append(state, previous, 7)
            previous = 7
            print(json.dumps({"width": n, "SG": model.algebra.value(state),
                              "nodes": len(model.algebra.nodes)}), flush=True)


if __name__ == "__main__":
    main()
