#!/usr/bin/env python3
"""Export certified full-core comb values within the C solver's 42 columns.

This is a bounded adapter, not a new proof or a certificate for arbitrary
three-row positions. --verify repeats the independent infinite-certificate
checks before exporting. --check detects stale generated data.
"""

import argparse
import contextlib
import hashlib
import io
from pathlib import Path
import sys

from parametric_comb_bridge import read_proof
from three_comb_chain import CertifiedThreeComb
from two_comb_core import CertifiedTwoComb

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "src/cfast/strip3_comb_tables.h"
MAXCOLS = 42


def array(name, values, ctype="uint8_t"):
    lines = [f"static const {ctype} {name}[{len(values)}] = {{"]
    lines += ["    " + ",".join(map(str, values[i:i + 24])) + ","
              for i in range(0, len(values), 24)]
    return "\n".join(lines + ["};", ""])


def generate(verify=False):
    paths = [ROOT / f"data/proofs/two_comb_strip_middle{w}.json.gz" for w in range(2, 6)]
    paths.append(ROOT / "data/proofs/three_comb_chain_2_3.json.gz")
    proofs = [read_proof(path) for path in paths]
    # Check the geometry as well as the proof format; roots/phases determine
    # which column word the recognizer is allowed to evaluate.
    sys.path.insert(0, str(ROOT / "tests"))
    from verify_three_comb_chain import check_geometry, verify as verify_chain
    from verify_two_comb_core import verify as verify_two
    for width, proof in zip(range(2, 6), proofs):
        check_geometry(proof, (6,) + (7,) * width + (6,))
        if verify:
            verify_two(proof)
    if proofs[-1]["widths"] != [2, 3]:
        raise ValueError("C recognizer requires widths 2,3")
    if verify:
        with contextlib.redirect_stdout(io.StringIO()):
            verify_chain(proofs[-1])
    lines = ["/* Generated by scripts/export_strip3_comb.py; do not edit.",
             " * Exact full-core families only, including all short/zero arms.",
             " * Certificate SHA256:"]
    lines += [f" * {path.name}: {hashlib.sha256(path.read_bytes()).hexdigest()}" for path in paths]
    lines += [" */", "#ifndef STRIP3_COMB_TABLES_H", "#define STRIP3_COMB_TABLES_H",
              f"#define STRIP3_COMB_MAXCOLS {MAXCOLS}", ""]
    # Pack each triangle in increasing left length, then right length.
    values, offsets = [], []
    for width, proof in zip(range(2, 6), proofs):
        offsets.append(len(values))
        query = CertifiedTwoComb(proof)
        budget = MAXCOLS - width - 2
        values += [query.value((left, right)) for left in range(budget + 1)
                   for right in range(budget - left + 1)]
    if max(values) >= 128:
        raise ValueError("SG value exceeds the C solver's supported range")
    lines += [array("strip3_single_offsets", offsets, "uint16_t"),
              array("strip3_single_values", values)]
    values, offsets = [], []
    query = CertifiedThreeComb(proofs[-1])
    for bridge in range(1, MAXCOLS - 9 + 1, 2):
        offsets.append(len(values))
        budget = MAXCOLS - 9 - bridge
        values += [query.query(left, right, bridge)["SG"] for left in range(budget + 1)
                   for right in range(budget - left + 1)]
    lines += [array("strip3_chain_offsets", offsets, "uint16_t"),
              array("strip3_chain_values", values), "#endif", ""]
    if max(values) >= 128:
        raise ValueError("SG value exceeds the C solver's supported range")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--verify", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = generate(args.verify)
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != content:
            raise SystemExit("stale comb tables: run make export-strip3-comb")
    else:
        OUTPUT.write_text(content)
    print(f"comb tables {'checked' if args.check else 'exported'}; independent verification={args.verify}")


if __name__ == "__main__":
    main()
